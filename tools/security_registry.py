#!/usr/bin/env python3
"""Собирает docs/SECURITY_STATUS.md: реестр находок аудитов (Sol = Codex gpt-6.1-sol, Sonnet = Claude) со статусами.

Заголовки, серьёзность и файлы берутся из отчётов аудитов (ANALYSIS10…14.md, папка передаётся аргументом); статусы и коммиты исправлений
заданы ниже вручную по истории git и ЯВНО помечены: чего нет — «нет данных» / «не проводилось». Ничего не выдумывается.
Запуск: python3 tools/security_registry.py /mnt/ssd480/yandi_codex_audit/sec3 > docs/SECURITY_STATUS.md
"""
import re, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "."
ROUNDS = {10: ("30", "ANALYSIS10.md"), 11: ("31", "ANALYSIS11.md"), 12: ("32", "ANALYSIS12.md"), 13: ("33", "ANALYSIS13.md"), 14: ("34", "ANALYSIS14.md")}

# id → (коммит исправления, примечание). Соответствие внутри круга 31 восстановлено по тексту сообщений коммитов.
FIX = {}
def rng(r, a, b, commit, note=""):
    for i in range(a, b + 1):
        FIX[f"P{r}-{i}"] = (commit, note)
rng(10, 1, 5, "05c0cbb"); rng(10, 6, 7, "2b53011"); rng(10, 8, 14, "d65cba7")
for i in (1, 2, 5, 8, 9, 13, 14):
    FIX[f"P11-{i}"] = ("5f05d79", "соответствие по тексту коммита")
for i in (4, 6, 7, 10, 11):
    FIX[f"P11-{i}"] = ("e181c8e", "соответствие по тексту коммита")
FIX["P11-12"] = ("3a0f056", "")
rng(12, 1, 8, "3290c25"); rng(13, 1, 8, "0e3e731"); rng(14, 1, 11, "5312040")
OPEN = {"P11-3": "Не исправлено (отложено решением: обновление прежних замков с четырьмя словами; в проекте на ранней стадии прежних установок нет). Остаётся открытой записью."}

def parse(round_no, fname):
    text = open(f"{SRC}/{fname}", encoding="utf-8").read()
    out = []
    for m in re.finditer(r"^## (P\d+-\d+) — (.+?)\n(.*?)(?=^## P\d+-\d+ — |^### |\Z)", text, re.S | re.M):
        pid, title, body = m.groups()
        sev = re.search(r"Серьёзность:\s*([^.\n]+)", body)
        files = re.search(r"Файл[ы]?:\s*([^\n]+)", body)
        out.append((pid, title.strip(), sev.group(1).strip() if sev else "нет данных", re.sub(r"\*\*\s*$", "", files.group(1)).strip()[:140].replace("|", "/") if files else "нет данных"))
    return out

print("# Реестр безопасности YANDI (SECURITY_STATUS)\n")
print("Единый перечень находок независимых проверок с постоянными номерами. Источники: **Sol** — Codex (модель gpt-6.1-sol), **Sonnet** — Claude, **GPT** — внешний аудит 2026-10-09.")
print("Старые отчёты не переписываются и остаются историческими свидетельствами; здесь записано, что реально устранено и чем это подтверждено. Реестр собран скриптом `tools/security_registry.py`; статусы заданы по истории git, отсутствующие сведения помечены прямо.\n")
print("## Статусы\n")
print("`Обнаружено` → `Подтверждено/воспроизведено` → `Исправлено в коде` → `Проверено автотестами` → `Проверено на устройствах` → `Закрыто`. Отдельно: `Не подтверждено`, `Отклонено с обоснованием`, `Риск принят`, `Открыто` (не смешиваются с успешным исправлением).")
print("**«Закрыто» не присвоено ни одной записи:** физических испытаний в сети из нескольких узлов и на нескольких устройствах по этим исправлениям пока не проводилось.\n")
print("## Открытые риски верхнего уровня\n")
print("| ID | Описание | Источник | Статус |\n|---|---|---|---|")
print("| R-1 | Возобновление сеанса по сохранённым секретам (`SessionToken.session_key_hex`, `resume_secret_hex`) хранится открытым hex в `paired_clients.json`/`paired_anchors.json`; нет прямой секретности возобновления | GPT (пп. 1–2 аудита 09.10), подтверждено чтением кода 18.10 | **Открыто.** Проект исправления — `docs/RESUME_REDESIGN.md` (до реализации, на независимой проверке) |")
print("| R-2 | Нет сквозного шифрования между узлами и с обычными контактами без зарегистрированного ключа (I2 «ждёт»); посредник может прочитать такую переписку | GPT (п. 6), `docs/CRYPTO_MAP.md` C2 | **Открыто** (архитектурное; проект E2E — отдельный документ) |")
print("| R-3 | `communication::E2EEncryption` — заглушка (п. 19 аудита 09.10) | GPT | Нет данных о текущем состоянии в реестре: сверить |")
print("| R-4 | Закрытая среда и служебные части узла запечатаны ключом устройства машины: компрометация работающей машины раскрывает их | `docs/PRIVACY.md` | **Риск принят** (узлу нужно работать без владельца), записан в документе |\n")
print("## Находки кругов 30–34 (Sol, независимые проверки)\n")
print("Круг → аудит: P10 = аудит 30, P11 = 31, P12 = 32, P13 = 33, P14 = 34. «Тесты»: автотесты запускались на коммите исправления и проходили (`cargo test --lib`, `flutter test`); имена тестов — в коммитах. «Устройства»: не проводилось.\n")
print("| ID | Описание | Источник | Серьёзность | Файлы | Статус | Коммит | Устройства |\n|---|---|---|---|---|---|---|---|")
total = fixed = 0
for r, (audit, fname) in ROUNDS.items():
    try:
        items = parse(r, fname)
    except FileNotFoundError:
        continue
    for pid, title, sev, files in items:
        total += 1
        if pid in OPEN:
            status, commit = "**Открыто.** " + OPEN[pid], "—"
        elif pid in FIX:
            fixed += 1
            commit, note = FIX[pid]
            nxt = "перепроверено следующим кругом" if r < 14 else "не перепроверено независимо"
            status = f"Исправлено в коде; проверено автотестами; {nxt}" + (f" ({note})" if note else "")
        else:
            status, commit = "Нет данных", "—"
        print(f"| {pid} | {title} | Sol, круг {audit} | {sev} | {files} | {status} | {commit} | не проводилось |")
print(f"\nИтого записей: {total}; исправлено в коде: {fixed}; открыто: {len(OPEN)}.\n")
print("## Внешний аудит GPT от 2026-10-09 (19 пунктов)\n")
print("Историческое свидетельство: `SECURITY_AUDIT_GPT.md`. Статус каждого пункта по коду ещё не сверен построчно; до сверки пункты не объявляются ни открытыми, ни закрытыми, кроме подтверждённых:\n")
print("| № | Тема | Статус в реестре |\n|---|---|---|")
for n, t, s in [
    (1, "Resume-токен не привязан к identity", "Частично: привязка к `node_id` есть (`resume_node_matches`, `node_id_hex`); полное закрытие — через R-1"),
    (2, "`session_key_hex` хранится открытым текстом", "**Открыто** (подтверждено 18.10), см. R-1"),
    (6, "Нет обязательного E2E между устройствами людей", "**Открыто**, см. R-2"),
]:
    print(f"| {n} | {t} | {s} |")
print("| 3–5, 7–19 | остальные пункты | Нет данных: сверка по коду не выполнена; будет добавлена построчно с коммитами и тестами |")
print("\n## Как обновлять\n")
print("Запись меняет статус только вместе с коммитом и тестом. Статус `Проверено на устройствах` — только по протоколу испытаний с версиями, командами и результатами. Новые круги аудита добавляются в `ROUNDS` и `FIX` скрипта.")
